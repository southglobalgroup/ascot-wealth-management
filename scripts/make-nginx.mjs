/* Writes nginx.conf.template: how the built site is served. The build makes one HTML file per page (/contact is contact.html), so the server only has to
   find that file, answer a real 404 for anything else, and keep ONE address per page. The old site's addresses ended in a slash (/contact/): those send on to
   the same page without it, and its addresses that are not pages now (src/data/routes.ts, moved) send on to where they lead. The container listens on $PORT (Cloud Run
   sets it); the nginx image fills ${PORT} in at start (NGINX_ENVSUBST_FILTER keeps it from touching the $variables nginx itself uses). The Dockerfile runs this script again inside the build, so the
   file that ships always follows src/data/site.ts: while `indexable` is false the server also says "noindex" in a header, and the day it is true the header goes by itself.
       node scripts/make-nginx.mjs */
import fs from 'node:fs'

/* the one place that decides whether search engines may list the site; unreadable means "keep out" */
const site = fs.readFileSync('src/data/site.ts', 'utf8')
const indexable = /indexable:\s*true\b/.test(site)
/* the old addresses that send on elsewhere (routes.ts `moved`: plain lower-case paths, a slash inside allowed:
   "/slide-page/banner"), read as text */
const routes = fs.readFileSync('src/data/routes.ts', 'utf8')
/* (a target may be a page in a folder, /services/steel-work) */
const moved = [...(routes.match(/export const moved[^=]*= \{([^}]*)\}/)?.[1] ?? '').matchAll(/'(\/[a-z0-9/-]+)':\s*'(\/[a-z0-9/.-]*)'/g)].map((m) => [m[1], m[2]])
/* whole folders of old addresses that send on to one page (routes.ts `movedPrefix`: "/tag/" -> "/blog") */
const movedPrefix = [...(routes.match(/export const movedPrefix[^=]*= \{([^}]*)\}/)?.[1] ?? '').matchAll(/'(\/[a-z0-9-]+\/)':\s*'(\/[a-z0-9-]*)'/g)].map((m) => [m[1], m[2]])

const SEC = [
  'add_header X-Content-Type-Options "nosniff" always;',
  'add_header Referrer-Policy "strict-origin-when-cross-origin" always;',
  'add_header X-Frame-Options "SAMEORIGIN" always;',
  /* geolocation stays allowed for this site itself: the price tool offers "Use my current location" */
  'add_header Permissions-Policy "geolocation=(self), microphone=(), camera=(), payment=()" always;',
  'add_header Strict-Transport-Security "max-age=31536000" always;',
  ...(indexable ? [] : ['add_header X-Robots-Tag "noindex, nofollow" always;']),
]
/* add_header in a location replaces the ones above it, so each location that sets its own repeats these */
const sec = (indent) => SEC.map((l) => indent + l).join('\n')

const conf = `# GENERATED by scripts/make-nginx.mjs. Do not edit by hand: change the script and run it again (the Dockerfile does, so the image never ships a stale one).
#
# How the built site is served (the nginx image fills in \${PORT}; Cloud Run ends TLS in front of it).
# One address per page: /contact is the page; /contact/ (the old site's form) and /contact.html send on to it.
# Search engines are ${indexable ? 'allowed (site.indexable is true)' : 'kept out (site.indexable is false): every response also carries X-Robots-Tag: noindex'}.
server {
    listen \${PORT};
    listen [::]:\${PORT};
    server_name _;
    root /usr/share/nginx/html;
    index index.html;
    charset utf-8;
    server_tokens off;

    # TLS is ended in front of nginx; without these a redirect would be sent to http://<host>:<port>/...
    absolute_redirect off;
    port_in_redirect off;
    server_name_in_redirect off;

    gzip on;
    gzip_vary on;
    gzip_min_length 256;
    gzip_proxied any;
    gzip_types text/plain text/css text/xml application/javascript application/json application/ld+json application/xml image/svg+xml;

${sec('    ')}

    # --- One address per page -----------------------------------------------------
    # The home page's own file name is not an address: /index.html and /index send on to /.
    location = /index.html { return 301 /$is_args$args; }
    location = /index { return 301 /$is_args$args; }

    # The old site's addresses that are not pages now send on, in one step, slash or no slash. Exact matches, so they win over the
    # folders below (/download/8189 is their panel's PDF; anything else under /download/ goes to the products page).
${moved.map(([from, to]) => `    location = ${from} { return 301 ${to}$is_args$args; }\n    location = ${from}/ { return 301 ${to}$is_args$args; }`).join('\n')}
    # And every address under these old folders (the blog's category, author and tag pages, their other downloads) goes to one page.
${movedPrefix.map(([from, to]) => `    location ^~ ${from} { return 301 ${to}; }`).join('\n')}

    # /contact/ is /contact, and /contact.html is /contact (the build has trailingSlash: 'never'). The part
    # that is carried over is allow-listed to the characters the page addresses use: a redirect that repeated whatever it was given (a decoded %5c, %09 or %0d) would be an open redirect,
    # because a browser reads a backslash or a tab after the first slash as a second slash. An address with anything else in it matches neither rule and is an ordinary 404.
    # The query string goes along, so that campaign links keep their tags.
    location ~ ^/([a-z0-9][a-z0-9/_.-]*)/$ {
        return 301 /$1$is_args$args;
    }
    location ~ ^/([a-z0-9][a-z0-9/_.-]*)[.]html$ {
        return 301 /$1$is_args$args;
    }

    # The 404 page is a file like any other; asked for by name it would come back 200, so both of its addresses answer 404.
    location = /404 { return 404; }

    location = / {
        try_files /index.html =404;
        add_header Cache-Control "no-cache, must-revalidate" always;
${sec('        ')}
    }

    location / {
        # /contact -> contact.html with no directory redirect in between, so the address served is the address in the canonical tag.
        try_files $uri $uri.html =404;
        add_header Cache-Control "no-cache, must-revalidate" always;
${sec('        ')}
    }

    # A folder with no index file (/_astro/, /docs/) would answer a bare nginx 403 page: it answers the 404 page like any other address that is not a page.
    # A malformed address (a stray % in a pasted link: /contact%) is nginx's own 400: it shows the same page, and keeps its 400.
    error_page 404 /not-found;
    error_page 403 =404 /not-found;
    error_page 400 /not-found;
    location = /not-found {
        internal;
        try_files /404.html =404;
        add_header Cache-Control "no-cache, must-revalidate" always;
${sec('        ')}
    }

    # --- Caching ------------------------------------------------------------------
    # Everything under /_astro/ has its content in its file name, so it can be kept for good. Pages are never cached, or a visitor
    # would be sent on to hashed files that a later build has removed.
    location ^~ /_astro/ {
        add_header Cache-Control "public, max-age=31536000, immutable";
${sec('        ')}
        access_log off;
    }

    # Pictures, favicons and the share card: a day.
    location ~* \\.(png|jpg|jpeg|webp|avif|gif|ico|svg|woff2|pdf)$ {
        add_header Cache-Control "public, max-age=86400";
${sec('        ')}
    }

    location ~* ^/(robots\\.txt|sitemap-index\\.xml|sitemap-0\\.xml)$ {
        add_header Cache-Control "public, max-age=3600";
${sec('        ')}
    }
}
`
fs.writeFileSync('nginx.conf.template', conf)
console.log(`nginx.conf.template written (search engines ${indexable ? 'allowed' : 'kept out, with a noindex header'})`)
